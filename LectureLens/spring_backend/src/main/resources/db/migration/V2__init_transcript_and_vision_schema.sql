CREATE TABLE IF NOT EXISTS transcripts (
    id VARCHAR(64) PRIMARY KEY,
    lecture_id VARCHAR(64) UNIQUE NOT NULL,
    full_text TEXT DEFAULT '',
    status VARCHAR(32) NOT NULL DEFAULT 'live' CHECK(status IN ('live', 'complete')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_transcripts_lecture FOREIGN KEY (lecture_id) REFERENCES lectures(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS transcript_segments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lecture_id VARCHAR(64) NOT NULL,
    chunk_id INTEGER,
    speaker_id VARCHAR(64),
    speaker_name VARCHAR(255),
    start_time DOUBLE PRECISION NOT NULL,
    end_time DOUBLE PRECISION,
    text TEXT NOT NULL,
    confidence DOUBLE PRECISION DEFAULT 1.0,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_segments_lecture FOREIGN KEY (lecture_id) REFERENCES lectures(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS board_contents (
    id VARCHAR(64) PRIMARY KEY,
    lecture_id VARCHAR(64) NOT NULL,
    timestamp DOUBLE PRECISION NOT NULL,
    image_path VARCHAR(512),
    extracted_text TEXT,
    equation TEXT,
    diagram_description TEXT,
    equations_json TEXT DEFAULT '[]',
    diagram_json TEXT DEFAULT '{}',
    key_points_json TEXT DEFAULT '[]',
    concept_diagram_json TEXT DEFAULT '{}',
    main_concept VARCHAR(255) DEFAULT '',
    structured_content_json TEXT DEFAULT '[]',
    image_hash VARCHAR(128) DEFAULT '',
    quality_score INTEGER DEFAULT 0,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_board_lecture FOREIGN KEY (lecture_id) REFERENCES lectures(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS screen_contents (
    id VARCHAR(64) PRIMARY KEY,
    lecture_id VARCHAR(64) NOT NULL,
    timestamp DOUBLE PRECISION NOT NULL,
    image_path VARCHAR(512),
    slide_title VARCHAR(255),
    extracted_text TEXT,
    code_snippet TEXT,
    diagram_description TEXT,
    equations_json TEXT DEFAULT '[]',
    diagram_json TEXT DEFAULT '{}',
    code_language VARCHAR(64) DEFAULT '',
    key_points_json TEXT DEFAULT '[]',
    concept_diagram_json TEXT DEFAULT '{}',
    main_concept VARCHAR(255) DEFAULT '',
    structured_content_json TEXT DEFAULT '[]',
    image_hash VARCHAR(128) DEFAULT '',
    quality_score INTEGER DEFAULT 0,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_screen_lecture FOREIGN KEY (lecture_id) REFERENCES lectures(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS multimodal_events (
    id VARCHAR(64) PRIMARY KEY,
    lecture_id VARCHAR(64) NOT NULL,
    timestamp DOUBLE PRECISION NOT NULL,
    title VARCHAR(255) NOT NULL,
    event_type VARCHAR(64) NOT NULL,
    audio_text TEXT,
    visual_content TEXT,
    combined_insight TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_events_lecture FOREIGN KEY (lecture_id) REFERENCES lectures(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_segments_lecture ON transcript_segments(lecture_id);
CREATE INDEX IF NOT EXISTS idx_segments_time ON transcript_segments(start_time);
CREATE INDEX IF NOT EXISTS idx_board_lecture ON board_contents(lecture_id);
CREATE INDEX IF NOT EXISTS idx_screen_lecture ON screen_contents(lecture_id);
CREATE INDEX IF NOT EXISTS idx_events_lecture ON multimodal_events(lecture_id);
